int
sys_kill(void)
{
  int pid;

  if(argint(0, &pid) < 0)
    return -1;
  return kill(pid);
}

int
sys_getpid(void)
{
  return myproc()->pid;
}

int
sys_sbrk(void)
{
  int addr;
  int n;

  if(argint(0, &n) < 0)
    return -1;
  addr = myproc()->sz;
  if(growproc(n) < 0)
    return -1;
  return addr;
}

int
sys_sleep(void)
{
  int n;
  uint ticks0;

  if(argint(0, &n) < 0)
    return -1;
  acquire(&tickslock);
  ticks0 = ticks;
  while(ticks - ticks0 < n){
    if(myproc()->killed){
      release(&tickslock);
      return -1;
    }
    sleep(&ticks, &tickslock);
  }
  release(&tickslock);
  return 0;
}

// return how many clock tick interrupts have occurred
// since start.
int
sys_uptime(void)
{
  uint xticks;

  acquire(&tickslock);
  xticks = ticks;
  release(&tickslock);
  return xticks;
}

int sys_yield(void)
{
	yield();
	return 0;
}


int sys_sched_setattr(void){

	int request_tick;
	int weight;

	if (argint(0, &request_tick)<0) return -1;
	if (argint(1, &weight) < 0 ) return -1;

	return sched_setattr(request_tick,weight);

}

int sys_sched_getattr(void) {

    int *request_tick, *weight;

    if (argptr(0, (void *)&request_tick, sizeof(int)) < 0)
        return -1;
    if (argptr(1, (void *)&weight, sizeof(int)) < 0)
        return -1;

    return sched_getattr(request_tick,weight);
}
